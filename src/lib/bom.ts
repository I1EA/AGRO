export type BomKind = "prototype" | "working";

export function linesFor(kind: BomKind): (BomLine & { qty: number })[] {
  return BOM.map((l) => ({
    ...l,
    qty: kind === "prototype" ? l.qtyPrototype : l.qtyWorking,
  })).filter((l) => l.qty > 0);
}

export function lineTotals(line: BomLine, qty: number) {
  const mad = toMad(line.unit, line.currency) * qty;
  const eur = toEur(line.unit, line.currency) * qty;
  return { mad, eur };
}

export function bomTotals(kind: BomKind) {
  return linesFor(kind).reduce(
    (acc, l) => {
      const t = lineTotals(l, l.qty);
      acc.mad += t.mad;
      acc.eur += t.eur;
      return acc;
    },
    { mad: 0, eur: 0 },
  );
}

